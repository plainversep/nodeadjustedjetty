#include <string>
#include <vector>

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void is_palindrome() {
    std::string text = "level";
    bool palindrome = true;
    for (std::size_t i = 0; i < text.size() / 2; ++i) {
        if (text[i] != text[text.size() - 1 - i]) { palindrome = false; break; }
    }
    (void)palindrome;
}

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

extern "C" int noble_canyon();
extern "C" void quiet_haven();
extern "C" void clever_vale();
extern "C" void frost_haven();
extern "C" void prime_canyon();

int main() {
    count_vowels();
    least_multiple();
    is_palindrome();
    gcd_triple();
    quiet_haven();
    clever_vale();
    frost_haven();
    prime_canyon();
    return noble_canyon();
}
